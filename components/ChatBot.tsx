const NORMALIZE_MAP: Record<string, string> = {
  ά: "α", έ: "ε", ή: "η", ί: "ι", ό: "ο", ύ: "υ", ώ: "ω",
  Ά: "α", Έ: "ε", Ή: "η", Ί: "ι", Ό: "ο", Ύ: "υ", Ώ: "ω",
  ϊ: "ι", ϋ: "υ", ΐ: "ι", ΰ: "υ",
};

function normalize(s: string): string {
  let out = s.toLowerCase();
  for (const [k, v] of Object.entries(NORMALIZE_MAP)) {
    out = out.split(k).join(v);
  }
  return out.trim();
}

function scoreQuestion(q: string): { index: number; count: number } | null {
  const nq = normalize(q);
  let best: { index: number; count: number } | null = null;
  KB_ENTRIES.forEach((e, i) => {
    const count = e.keywords.filter((k) => nq.includes(normalize(k))).length;
    if (count > 0 && (!best || count > best.count)) best = { index: i, count };
  });
  return best;
}

const FALLBACK =
  "Δεν είμαι απόλυτα σίγουρος για αυτό — οι απαντήσεις μου είναι ενδεικτικές. Δοκίμασε κάποια από αυτά τα θέματα ή συμβουλέψου έναν λογιστή για την ακριβή περίπτωσή σου.";

export function ChatBot() {
  const [open, setOpen] = useState(false);
  const [msgs, setMsgs] = useState<Msg[]>([
    {
      from: "bot",
      text: "Γεια σου! Είμαι ο βοηθός της GreekTax 🇬🇷 Σε ρωτάς, σου απαντάω — δωρεάν. Τι θες να μάθεις για τους φόρους ή τα εργαλεία;",
    },
  ]);
  const [input, setInput] = useState("");
  const [typing, setTyping] = useState(false);
  const listRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    listRef.current?.scrollTo({ top: listRef.current.scrollHeight });
  }, [msgs, typing, open]);

  const answer = (q: string) => {
    const best = scoreQuestion(q);
    const text = best ? KB_ENTRIES[best.index].answer : FALLBACK;
    setTyping(true);
    setMsgs((m) => [...m, { from: "bot", text }]);
    setTyping(false);
  };

  const send = async (raw: string) => {
    const text = raw.trim();
    if (!text) return;
    setMsgs((m) => [...m, { from: "user", text }]);
    setInput("");
    await new Promise((r) => setTimeout(r, 350));
    answer(text);
  };

  return (
    <>
      <button
        type="button"
        className="chat-fab"
        aria-label="Άνοιξε τον βοηθό"
        onClick={() => setOpen((o) => !o)}
      >
        {open ? "✕" : "💬"}
      </button>

      {open && (
        <div className="chat-panel" role="dialog" aria-label="Βοηθός GreekTax">
          <div className="chat-head">
            <span className="chat-avatar">🤖</span>
            <div>
              <b>Βοηθός GreekTax</b>
              <small>Απαντάει άμεσα, δωρεάν</small>
            </div>
          </div>

          <div className="chat-body" ref={listRef}>
            {msgs.map((m, i) => (
              <div key={i} className={`chat-msg ${m.from}`}>
                {m.text}
              </div>
            ))}
            {typing && <div className="chat-msg bot typing">…</div>}
          </div>

          <div className="chat-quick">
            {QUICK_TOPICS.map((t) => (
              <button key={t} type="button" onClick={() => void send(t)}>
                {t}
              </button>
            ))}
          </div>

          <form
            className="chat-input"
            onSubmit={(e) => {
              e.preventDefault();
              void send(input);
            }}
          >
            <input
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Ρώτα με…"
              aria-label="Το ερώτημά σου"
            />
            <button type="submit" aria-label="Στείλε">➤</button>
          </form>
        </div>
      )}
    </>
  );
}